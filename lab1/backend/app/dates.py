"""Поводы и фразы по дате: праздники, сезонные строки, промпт для LLM."""
import datetime
from zoneinfo import ZoneInfo

# (месяц, день) -> (название повода, форма для фразы «С ...» — творительный падеж)
HOLIDAYS: dict[tuple[int, int], tuple[str, str]] = {
    (1, 1): ("Новый год", "Новым годом"),
    (3, 8): ("8 Марта", "8 Марта"),
    (4, 12): ("День космонавтики", "Днём космонавтики"),
    (5, 1): ("Праздник весны и труда", "Праздником весны и труда"),
    (5, 9): ("День Победы", "Днём Победы"),
    (6, 1): ("первый день лета", "первым днём лета"),
    (6, 6): ("День русского языка", "Днём русского языка"),
    (9, 1): ("День знаний", "Днём знаний"),
    (10, 5): ("День учителя", "Днём учителя"),
    (11, 4): ("День народного единства", "Днём народного единства"),
    (12, 31): ("канун Нового года", "наступающим Новым годом"),
}

# сезонная фраза по номеру месяца (зима: 12, 1, 2; весна: 3-5; лето: 6-8; осень: 9-11)
SEASONS: dict[int, str] = {
    12: "Зимнего настроения!", 1: "Зимнего настроения!", 2: "Зимнего настроения!",
    3: "Весеннего настроения!", 4: "Весеннего настроения!", 5: "Весеннего настроения!",
    6: "Хорошего летнего дня!", 7: "Хорошего летнего дня!", 8: "Хорошего летнего дня!",
    9: "Тёплого осеннего дня!", 10: "Тёплого осеннего дня!", 11: "Тёплого осеннего дня!",
}


def today(tz: str, now: datetime.datetime | None = None) -> datetime.date:
    """Возвращает календарную дату в заданном часовом поясе."""
    if now is None:
        now = datetime.datetime.now(datetime.timezone.utc)
    return now.astimezone(ZoneInfo(tz)).date()


def describe_date(d: datetime.date) -> tuple[str | None, str]:
    """Возвращает (название повода | None, сезонная фраза)."""
    entry = HOLIDAYS.get((d.month, d.day))
    return (entry[0] if entry else None), SEASONS[d.month]


def greeting_phrase(d: datetime.date) -> str:
    """Готовый fallback-текст: «С <поводом в творительном падеже>!» или сезонная фраза."""
    entry = HOLIDAYS.get((d.month, d.day))
    if entry:
        return f"С {entry[1]}! Пусть этот день принесёт только хорошее."
    return SEASONS[d.month]


def build_prompt(d: datetime.date) -> str:
    holiday, seasonal = describe_date(d)
    occasion = holiday if holiday else seasonal
    return (f"Дата: {d.isoformat()}. Повод: {occasion}. "
            "Напиши короткое тёплое поздравление (1–3 предложения) на русском.")
